export type ScriptTargetEngine =
  | 'supabase'
  | 'postgresql'
  | 'mysql'
  | 'sqlite'
  | 'firestore';

export interface ScriptGeneratorOptions {
  engine: ScriptTargetEngine;
  schemaName: string;
  tablePrefix: string;
  includeIndexes: boolean;
  includeSeedData: boolean;
}

function cleanIdent(raw: string, fallback: string): string {
  const cleaned = raw.trim().replace(/[^a-zA-Z0-9_]/g, '');
  return cleaned || fallback;
}

