function buildFirestoreScript(): string {
  return [
    `// ============================================================================`,
    `// CLOUD FIRESTORE — KONFIGURASI KOLEKSI & SECURITY RULES`,
    `// Firebase Project ID : ${FIREBASE_APPLET_META.projectId}`,
    `// Firestore Database  : ${FIREBASE_APPLET_META.firestoreDatabaseId}`,
    `// ============================================================================`,
    ``,
    `// Daftar Koleksi Firestore yang Digunakan:`,
    `// 1. /test/connection                 -> Health check koneksi Firestore`,
    `// 2. /appSettings/{settingId}         -> Pengaturan perusahaan & jumlah shift`,
    `// 3. /employees/{employeeId}          -> Data master karyawan & jadwal libur`,
    `// 4. /attendance/{recordId}           -> Catatan absensi & izin datang terlambat`,
    `// 5. /lateSettlements/{settlementId}  -> Penyelesaian / kompensasi terlambat`,
    `// 6. /financeAccounts/{accountId}     -> Akun kas tunai & rekening bank`,
    `// 7. /financeCategories/{categoryId}  -> Kategori pendapatan & pengeluaran`,
    `// 8. /financeTransactions/{txId}      -> Jurnal transaksi kas & transfer`,
    `// 9. /financeTransfers/{transferId}   -> Perpindahan dana antar akun`,
    ``,
    `rules_version = '2';`,
    `service cloud.firestore {`,
    `  match /databases/{database}/documents {`,
    `    match /{document=**} { allow read, write: if false; }`,
    `    // Koleksi admin & operasional tervalidasi penuh di file /firestore.rules`,
    `    // dan sudah di-deploy ke database ${FIREBASE_APPLET_META.firestoreDatabaseId}.`,
    `  }`,
    `}`,
  ].join('\n');
}

export function generateDatabaseSetupScript(opts: ScriptGeneratorOptions): {
  code: string;
  filename: string;
  languageLabel: string;
} {
  switch (opts.engine) {
    case 'supabase':
      return {
        code: buildPostgresScript(opts, true),
        filename: 'karyapresensi-schema-supabase.sql',
        languageLabel: 'Supabase PostgreSQL + RLS (.sql)',
      };
    case 'postgresql':
      return {
        code: buildPostgresScript(opts, false),
        filename: 'karyapresensi-schema-postgresql.sql',
        languageLabel: 'PostgreSQL DDL (.sql)',
      };
    case 'mysql':
      return {
        code: buildMysqlScript(opts),
        filename: 'karyapresensi-schema-mysql.sql',
        languageLabel: 'MySQL / MariaDB DDL (.sql)',
      };
    case 'sqlite':
      return {
        code: buildSqliteScript(opts),
        filename: 'karyapresensi-schema-sqlite.sql',
        languageLabel: 'SQLite 3 DDL (.sql)',
      };
    case 'firestore':
      return {
        code: buildFirestoreScript(),
        filename: 'karyapresensi-firestore-setup.rules',
        languageLabel: 'Cloud Firestore Rules & Collections',
      };
  }
}
